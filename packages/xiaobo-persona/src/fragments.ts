/**
 * Canonical Xiaobo prompt fragments.
 *
 * Each fragment is data, not control flow: the plugin registers one section per
 * fragment, and a deployment overrides the text (or drops the section) through
 * config. Keeping the text here gives every section a single source.
 *
 * `en` is the wire text currently shipped by the MiMo route prompts; `zh` is the
 * original Chinese persona recovered from the deleted `xiaobo.txt`, which is the
 * more complete wording and the intended source for future edits.
 *
 * None of the shipped text contains a `{{…}}` group, so the registry's default
 * interpolation is safe; a deployment that overrides a fragment with literal
 * braces should set `interpolate: false`.
 *
 * @module dsh-xb-xiaobo-persona/fragments
 */

/** Locale of the shipped fragment text. */
export type Locale = 'en' | 'zh'

/** Every locale a fragment ships in. */
export interface Fragment {
  readonly en: string
  readonly zh: string
}


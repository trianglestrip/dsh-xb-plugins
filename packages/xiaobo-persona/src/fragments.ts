/**
 * Read one fragment in the requested locale.
 * @param fragment - fragment carrying both shipped locales.
 * @param locale - locale to read.
 * @returns the fragment's text for that locale.
 */
export function renderFragment(fragment: Fragment, locale: Locale): string {
  return fragment[locale]
}
